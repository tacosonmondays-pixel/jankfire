// node tools/city/heart_boxes.mjs [--check]
// The Big Heart's collision, from the model's own json (public/models/story/s_gut_heart.json, written by
// tools/blender/make_gut_heart.py) into shared/city/bigheart_boxes.js: the chunk generators run in workers and on the
// server, where there's no fetch, so the boxes ship as a module. Run it again whenever the model is rebuilt.
// --check: exit 1 if the module is stale (tests/story/bigheart.test.mjs runs it).
import fs from 'node:fs';
const J = JSON.parse(fs.readFileSync(new URL('../../public/models/story/s_gut_heart.json', import.meta.url), 'utf8'));
const out = new URL('../../shared/city/bigheart_boxes.js', import.meta.url);
const r2 = (v) => Math.round(v * 100) / 100, box = (b) => b.map(r2);
// the thigh-bone buttresses: the json boxes each one as five fat slabs (2 x 3 x 2 m round a 0.8 m bone), and those
// slabs fill the first two turns of the stair. so each bone is boxed again here, thin: N short boxes along its axis
// (the axis and the bone's length come out of the json's own five), and where the bone crosses over a tread the box
// that would take a climber's headroom is left out: you brush through the bone there instead of being walled off
const N = 12, HEAD = 1.85, femurs = [];
const ov = (a, b) => a[0] < b[3] && a[3] > b[0] && a[1] < b[4] && a[4] > b[1] && a[2] < b[5] && a[5] > b[2];
// (the first treads are sunk in the mound: there you stand on the mound, so the headroom starts from its top)
const floorAt = (s) => Math.max(s[4], ...J.boxes.mound.filter((m) => s[0] < m[3] && s[3] > m[0] && s[2] < m[5] && s[5] > m[2]).map((m) => m[4]));
const headroom = J.boxes.steps.map((s) => [s[0] + 0.05, s[4] + 0.05, s[2] + 0.05, s[3] - 0.05, floorAt(s) + HEAD, s[5] - 0.05]);
let cut = 0;
for (let g = 0; g * 5 < J.boxes.buttresses.length; g++) {
  const bs = J.boxes.buttresses.slice(g * 5, g * 5 + 5), c = (b) => [(b[0] + b[3]) / 2, (b[1] + b[4]) / 2, (b[2] + b[5]) / 2];
  const c1 = c(bs[1]), c4 = c(bs[4]), d = c1.map((v, k) => (c4[k] - v) / 3); // (the first slab is clipped at the ground: measure from the second)
  const foot = c1.map((v, k) => v - d[k] * 1.5), head = c4.map((v, k) => v + d[k] * 0.5), L = Math.hypot(...d) * 5, r = 0.036 * L * 1.03; // the shaft's radius (make_gut_heart.py femur_prim)
  for (let i = 0; i < N; i++) {
    const a = foot.map((v, k) => v + (head[k] - v) * i / N), b = foot.map((v, k) => v + (head[k] - v) * (i + 1) / N), rr = i === 0 ? r * 1.8 : r; // the knee is the fat end
    const q = [Math.min(a[0], b[0]) - rr, Math.max(0, Math.min(a[1], b[1]) - rr), Math.min(a[2], b[2]) - rr, Math.max(a[0], b[0]) + rr, Math.max(a[1], b[1]) + rr, Math.max(a[2], b[2]) + rr];
    if (headroom.some((h) => ov(q, h))) { cut++; continue; }
    femurs.push(q);
  }
}
// the spine: the json has it as ten 3 m square lifts, whose corners stick 0.4 m out of the round spine and catch
// heads and treads on the way up (it leans as it climbs). so it's boxed again from the stair's own axis (centre and
// radius every 1.5 m): three boxes a lift, a square and a cross, all inside the circle
const tower = [], AX = J.stair.axis, topY = J.size.spine_top_y;
for (let i = 0; i < AX.length; i++) {
  const a = AX[i], b = AX[i + 1] || a, y0 = a[0], y1 = AX[i + 1] ? b[0] : topY, cx = (a[1] + b[1]) / 2, cz = (a[2] + b[2]) / 2, r = (a[3] + b[3]) / 2;
  for (const [hx, hz] of [[0.7, 0.7], [0.94, 0.34], [0.34, 0.94]]) tower.push([cx - hx * r, y0, cz - hz * r, cx + hx * r, y1, cz + hz * r]);
}
const data = {
  boxes: { ...Object.fromEntries(['mound', 'steps', 'heart'].map((k) => [k, J.boxes[k].map(box)])), tower: tower.map(box), buttresses: femurs.map(box) },
  // the stair as the model built it: [y, x, z, state] per tread (0 ok, 1 stub = half a tread, 2 gone = a gap)
  treads: J.stair.list.map((t) => [r2(t.y), r2(t.mid[0]), r2(t.mid[2]), ['ok', 'stub', 'gone'].indexOf(t.state)]),
  axis: J.stair.axis.map((a) => a.map(r2)), // the spine's centre line: [y, x, z, radius] every 1.5 m (it leans)
  markers: Object.fromEntries(['listening_spot', 'stair_foot', 'first_tread', 'stair_top', 'apex', 'heart_centre', 'pacemaker', 'top', 'glow_light'].map((k) => [k, J.markers[k].map(r2)])),
  size: { min: J.size.min, max: J.size.max },
};
const src = '// generated by tools/city/heart_boxes.mjs from public/models/story/s_gut_heart.json: the Big Heart\'s collision\n'
  + '// boxes ([x0, y0, z0, x1, y1, z1], model space, metres), its stair and markers. don\'t edit\nexport default ' + JSON.stringify(data) + ';\n';
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== src) { console.error('shared/city/bigheart_boxes.js is stale: run node tools/city/heart_boxes.mjs'); process.exit(1); }
  console.log('bigheart_boxes.js is up to date');
} else { fs.writeFileSync(out, src); console.log('wrote shared/city/bigheart_boxes.js:', Object.entries(data.boxes).map(([k, v]) => v.length + ' ' + k).join(', '), '(' + cut + ' bone boxes left out over the stair)'); }
