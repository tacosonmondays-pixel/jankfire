# writes roblox/studio-tools/<Module>.luau from a hub kit's <name>_layout.json (hubshape.coll boxes): the unseen
# collision boxes in the hub's site frame, one source of numbers for the meshes and the Luau builder.
# run: py hub_data.py <layout.json> <ModuleName>      (THE STILL keeps its own still_data.py; same format)
import json, sys, os
src, mod = sys.argv[1], sys.argv[2]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'roblox', 'studio-tools', mod + '.luau')
d = json.load(open(src))
lines = ['--!nonstrict', '-- GENERATED by tools/roblox/hub_data.py from %s: do not edit by hand.' % os.path.basename(src),
         '-- coll: { name, px, py, pz, sx, sy, sz, yaw, pitch, roll } in the site frame (x east, y up, z south); the builder',
         '-- makes each an unseen solid box.', 'return {', '\tcoll = {']
for c in d['coll']:
    p, s, r = c['p'], c['s'], c['r']
    lines.append('\t\t{ "%s", %g, %g, %g, %g, %g, %g, %g, %g, %g },' % (c['name'], p[0], p[1], p[2], s[0], s[1], s[2], r[0], r[1], r[2]))
lines += ['\t},', '}', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', out, len(d['coll']), 'boxes')
