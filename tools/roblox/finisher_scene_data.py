# The in-game finisher scenes' data (19 Nov): the moving cut that finisher_r15.py plans for the videos (video:<v>),
# boiled down to what the game plays per frame - the lens (stage-local CFrame, FOV), each body's clip and moment and
# where its root stands, where the katana is - plus the fixed set (floor, pillars, trees). client/FinisherScene.luau
# plays it on the killer's and the victim's own avatars with the uploaded mocap animations (Finishers.SCENE_ANIMS).
# run: py tools/roblox/finisher_scene_data.py <out.luau> <scene id>=<video_dir> [<scene id>=<video_dir> ...]
import json, os, sys


def r(x, n=3):
    v = round(float(x), n)
    return '0' if v == 0 else repr(v)


def cf(c):
    return '{' + ','.join([r(v, 3) for v in c[:3]] + [r(v, 4) for v in c[3:]]) + '}'


def scene(sid, vdir):
    frames = json.load(open(os.path.join(vdir, 'frames.json')))
    shots = json.load(open(os.path.join(vdir, 'shots.json')))
    keys = sorted(k for k in frames if not k.startswith('_'))
    clips = []
    for k in keys:
        for a in frames[k].get('anim', {}).values():
            if a['clip'] not in clips:
                clips.append(a['clip'])
    out = [f'\t{sid} = {{', f'\t\tfps = {shots["fps"]},',
           '\t\tclips = { ' + ', '.join(f'"{c}"' for c in clips) + ' },',
           '\t\tshots = { ' + ', '.join(f'{{ "{n}", {c} }}' for n, c in shots['shots']) + ' },']
    st = frames.get('_stage', {}).get('props', [])
    out.append('\t\tstage = {')
    for p in st:
        s, c = p['size'], p['col']
        out.append(f'\t\t\t{{ "{p["shape"]}", {r(s[0])}, {r(s[1])}, {r(s[2])}, {cf(p["cf"])}, {r(c[0])}, {r(c[1])}, {r(c[2])}, "{p["mat"]}", "{p["tag"]}" }},')
    out.append('\t\t},')
    out.append('\t\tf = {')
    for k in keys:
        f = frames[k]
        parts = [f'c = {cf(f["lens"]["cf"])}', f'fov = {r(f["lens"]["fov"], 2)}']
        for n, a in sorted(f.get('anim', {}).items()):
            parts.append(f'{n} = {{ {clips.index(a["clip"]) + 1}, {r(a["t"], 4)}, {cf(a["root"])}, {r(a.get("sc", 0))} }}')
        kat = f.get('kat') or []
        if kat:
            m = kat[0]
            parts.append('kat = { 1 }' if m['mode'] == 'hand' else (f'kat = {{ 2, {cf(m["rel"])} }}' if m['mode'] == 'lt' else 'kat = { 0 }'))
        if f.get('impact'):
            parts.append('hit = true')
        out.append('\t\t\t{ ' + ', '.join(parts) + ' },')
    out.append('\t\t},')
    out.append('\t},')
    return out


def main():
    dst = sys.argv[1]
    body = []
    for a in sys.argv[2:]:
        sid, vdir = a.split('=', 1)
        body += scene(sid, vdir)
    head = ['--!strict',
            '-- FINISHER SCENE DATA - generated by tools/roblox/finisher_scene_data.py from the video plan of',
            '-- tools/roblox/finisher_r15.py (video:<v>); do not edit by hand, rebuild it. Per frame (24 fps): c = the lens',
            '-- (CFrame components, stage-local), fov, k / v = { clip index, clip time, the root CFrame, scatter }, kat = where',
            '-- the katana is (1 = the killer\'s right hand, 2 = { 2, its CFrame from the killer\'s LowerTorso }), hit = a',
            '-- two-tone hit frame. Stage-local = 600 studs over the scene\'s origin; the stage list is the fixed set.',
            'return {']
    open(dst, 'w', encoding='utf8', newline='\n').write('\n'.join(head + body + ['} :: any', '']))
    print('wrote', dst, os.path.getsize(dst))


main()
