# writes roblox/studio-tools/HubStillData.luau from still_models.py's still_layout.json: the unseen collision boxes of
# THE STILL in the site frame (one source of numbers for the meshes and the builder). run: py still_data.py <layout.json>
import json, sys, os
src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'roblox', 'studio-tools', 'HubStillData.luau')
d = json.load(open(src))
lines = ['--!nonstrict', '-- GENERATED by tools/roblox/still_data.py from still_models.py (THE STILL\'s kit): do not edit by hand.',
         '-- coll: { name, px, py, pz, sx, sy, sz, yaw, pitch, roll } in the site frame (x east, y up, z south); the builder',
         '-- makes each an unseen solid box (CraterFloor: a cylinder along its x).', 'return {', '\tcoll = {']
for c in d['coll']:
    p, s, r = c['p'], c['s'], c['r']
    lines.append('\t\t{ "%s", %g, %g, %g, %g, %g, %g, %g, %g, %g },' % (c['name'], p[0], p[1], p[2], s[0], s[1], s[2], r[0], r[1], r[2]))
lines += ['\t},', '}', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', out, len(d['coll']), 'boxes')
