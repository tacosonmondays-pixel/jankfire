# Where each weapon hat sits (tools/roblox/hat_spots.json) and how high: the top of the gun under the spot, measured on
# the live gun set itself (gun_set.py builders; --set kit = gun_models.py) with a ray straight down. Headless Blender:
#
#   blender -b --factory-startup -P tools/roblox/hat_spots.py -- [--set kit] [--profile <id> ...]
#
# writes roblox/src/shared/GunHatData.luau: the hats (names, rarities, file bounds from roblox/assets/hats/hats.json),
# the spot on every gun (metres, the weapon frame) and the moving bits. --profile prints a gun's top line (every cm
# along it) to pick a spot from. RUN IT AGAIN AFTER ANY GUN REMODEL: a hat sits on the surface measured here.
#
# hat_spots.json, per weapon: z (along the gun, metres, -z = toward the muzzle), x (sideways, default 0), s (the hat's
# size, 1 = as built, about 7 cm across), yaw (degrees, default 0), sink (metres the foot goes into the surface,
# default 0.002), y (a fixed height instead of the measured one), note (why it sits there).
import bpy, bmesh, sys, os, json, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mathutils import Vector
from mathutils.bvhtree import BVHTree
import hat_models
# the guns the hats sit on: the live set (gun_set.py, the owner's A/B/C picks) unless --set kit (gun_models.py, round 8)
if '--set' in sys.argv and sys.argv[sys.argv.index('--set') + 1] == 'kit':
    import gun_models as GUNS
else:
    import gun_set as GUNS

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')


def build(wid):
    """a gun, or a skin of one ("ar@cardboard": gun_set.SKINS)"""
    if '@' in wid: return GUNS.SKINS[wid]()
    return GUNS.BUILD[wid]()


def tree(wid):
    g = build(wid)
    bm = bmesh.new()
    for b in g.pieces.values():
        me = bpy.data.meshes.new('t'); b.to_mesh(me); bm.from_mesh(me); bpy.data.meshes.remove(me)
    t = BVHTree.FromBMesh(bm)
    lo, hi = g.bounds()
    bm.free()
    return t, lo, hi


def top(t, x, z, above=1.0):
    """the highest surface at (x, z) in the weapon frame (Blender: x, -z, y)"""
    hit = t.ray_cast(Vector((x, -z, above)), Vector((0, 0, -1)))
    return None if hit[0] is None else hit[0].z


def lua_vec(v): return 'Vector3.new(%s)' % ', '.join('%g' % round(c, 5) for c in v)


def main():
    argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    if '--profile' in argv:
        for wid in argv[argv.index('--profile') + 1:]:
            t, lo, hi = tree(wid)
            print('PROFILE', wid, 'lo', lo, 'hi', hi)
            z = lo[2]
            while z <= hi[2]:
                row = []
                for x in (-0.015, 0.0, 0.015):
                    y = top(t, x, z)
                    row.append('   --  ' if y is None else '%7.4f' % y)
                print('  z %7.3f  y(x=-1.5cm, 0, +1.5cm) %s' % (z, ' '.join(row)))
                z += 0.01
        return
    spots = json.load(open(os.path.join(HERE, 'hat_spots.json')))
    hats = json.load(open(os.path.join(ROOT, 'roblox', 'assets', 'hats', 'hats.json')))
    assets = {}
    ap = os.path.join(ROOT, 'roblox', 'assets', 'hats', 'assets.json')
    if os.path.exists(ap): assets = json.load(open(ap))
    out = []
    w = out.append
    w('--!strict')
    w('-- GENERATED by tools/roblox/hat_spots.py from tools/roblox/hat_spots.json, roblox/assets/hats/hats.json and')
    w('-- tools/roblox/hat_models.py. Do not edit: change those and run it again (README in roblox/docs/GUN-HATS.md).')
    w('local D = {}')
    w('')
    w('-- the hats, in the loadout\'s order (shared/cosmetics.js COSMETICS.hat). "none" = no hat. vip = VIP only: in no')
    w('-- container and no shop rotation, worn on every gun once owned (LootTable.vipOnly)')
    w('D.ORDER = { "none", %s }' % ', '.join('"%s"' % h for h in hat_models.HATS))
    w('D.HATS = {')
    w('\tnone = { name = "None", rarity = "free" },')
    for h in hat_models.HATS:
        b = hats.get(h)
        vip = ', vip = true' if h in getattr(hat_models, 'VIP', ()) else ''
        w('\t%s = { name = "%s", rarity = "%s"%s, lo = %s, hi = %s },' % (h, hat_models.NAMES[h], hat_models.RARITY[h], vip,
          lua_vec(b['lo']) if b else 'nil', lua_vec(b['hi']) if b else 'nil'))
    w('}')
    w('-- the upload (every hat in one model, 10 x size: one template stud = UNIT metres)')
    w('D.ASSET = %s' % (assets.get('hats') or 0))
    w('D.UNIT = %g' % (1.0 / hat_models.UNIT))
    w('')
    w('-- the moving bits (client only): spin = round the hat\'s up axis (rad/s), bob = up and down (metres, Hz),')
    w('-- rattle = jitter in the plane u, v (metres; the googly pupils)')
    w('D.MOVES = {')
    for h, nodes in hat_models.MOVES.items():
        parts = []
        for n, m in nodes.items():
            kv = ['kind = "%s"' % m['kind']]
            for k in ('speed', 'amp'):
                if k in m: kv.append('%s = %g' % (k, m[k]))
            for k in ('u', 'v'):
                if k in m: kv.append('%s = %s' % (k, lua_vec(m[k])))
            parts.append('%s = { %s }' % (n, ', '.join(kv)))
        w('\t%s = { %s },' % (h, ', '.join(parts)))
    w('}')
    w('')
    w('-- where the hat sits on each weapon: at = the foot of the hat (metres, the weapon frame: x right, y up, z back,')
    w('-- the same frame as Weapons.luau mdl), s = its size (1 = as built, ~7 cm across), yaw = degrees round its up axis,')
    w('-- pitch = degrees about x after that (90: the hat stands on the back end, the katana\'s pommel), saddle = metres:')
    w('-- the hat stands that much higher on a slate puck (a round scope or barrel under a flat foot).')
    w('-- y was measured on the kit model (the top of the gun under the spot)')
    w('-- a skin ("<gun>@<skin>", gun_set.py SKINS) has its own line: its gun spot (or its own in hat_spots.json) with the')
    w('-- height measured on the skin model. GunHats uses it when the built gun carries the attribute Skin = "<skin>"')
    w('D.SPOTS = {')
    # every skin in the gun set gets a seat: its own line in hat_spots.json, or its gun's
    for key in sorted(getattr(GUNS, 'SKINS', {})):
        base = key.split('@')[0]
        if key not in spots and base in spots:
            sp = dict(spots[base]); sp['note'] = "skin: its gun's spot, height measured on the skin"
            if sp.get('pitch') != 90: sp.pop('y', None)  # (a hat on the back end keeps its height: the handle's axis)
            spots[key] = sp
    for wid, sp in spots.items():
        if wid.startswith('_'): continue
        x, z = sp.get('x', 0.0), sp['z']
        if 'y' in sp:
            y = sp['y'] - sp.get('sink', 0.0)
        else:
            t, lo, hi = tree(wid)
            y = top(t, x, z)
            if y is None: raise SystemExit('%s: nothing under the spot (%g, %g)' % (wid, x, z))
            y -= sp.get('sink', 0.002)
        note = sp.get('note', '')
        sad = (', saddle = %g' % sp['saddle']) if sp.get('saddle') else ''
        w('\t%s = { at = %s, s = %g, yaw = %g, pitch = %g%s },%s' % (wid if '@' not in wid else '["%s"]' % wid, lua_vec((x, y, z)), sp.get('s', 1.0), sp.get('yaw', 0), sp.get('pitch', 0), sad,
          ('  -- ' + note) if note else ''))
        print('SPOT', wid, round(x, 4), round(y, 4), round(z, 4), 's', sp.get('s', 1.0))
    w('}')
    w('')
    w('return D')
    path = os.path.join(ROOT, 'roblox', 'src', 'shared', 'GunHatData.luau')
    open(path, 'w', encoding='utf8', newline='\n').write('\n'.join(out) + '\n')
    print('WROTE', path)


main()
