# Writes roblox/src/shared/Holds.luau: how each weapon is held in first person, for AvatarArms.luau and Viewmodel.luau.
# From tools/roblox/holds.json (the table, tuned in hold_preview.py and in Play tests) and the katana's rest pose and
# clips (Weapons.luau, Anims.luau).
# run: py tools/roblox/holds.py
import json, math, os
import holds_lib as L

H = L.load_holds()


def f(x): return ('%.5f' % x).rstrip('0').rstrip('.') if abs(x) > 5e-6 else '0'
def V(v): return 'V(%s)' % ', '.join(f(c) for c in v)
def CF(Rm): return 'CFrame.new(0, 0, 0, %s)' % ', '.join(f(Rm[i][j]) for i in range(3) for j in range(3))


out = ['--!strict',
       '-- GENERATED by tools/roblox/holds.py from tools/roblox/holds.json: do not edit by hand. How each weapon is held in',
       '-- first person (AvatarArms.luau puts your avatar\'s hands on it from this).',
       '--   holds[weapon][side]: pose = what kind of hold (grip / fist / cradle / wrap: the thing runs through the fist;',
       '--     palm: held from under), at = where the fist is on the weapon (file metres), rot = radians (x, y, z as',
       '--     CFrame.Angles): +Y runs along the thing held, toward the thumb (palm: up into it); size = the hand against',
       '--     AvatarArms.HAND; elbow = this arm\'s own elbow spot; turn = an extra turn about the handle (radians)',
       '--   holds[weapon].shift: a move of the weapon\'s rest pose, camera space (metres); scale: its size against size;',
       '--     tilt: a turn added to its rest pose (radians, x y z like vm.r)',
       '--   holds[weapon].ads: the aimed view (Viewmodel.adsPos). aimZ = the sight this much further from your eye (metres,',
       '--     on top of 0.17; the zoom\'s own push comes on top of that), sight = where the aim line runs on the gun (file',
       '--     metres; else the gun\'s own Sight spot), kind = iron / dot / none / scope (the HUD: the crosshair goes for',
       '--     sights, a red dot shows in a dot sight), skins[id] = a skin\'s own aimZ / sight, hide = its pieces (names',
       '--     start with these) faded out while aiming: wings, horns, crowns; near = its big pieces by the stock drawn',
       '--     smaller in your own first-person view only (pieces, scale, pivot in file metres)',
       '--   elbow: where each forearm comes from, in camera space (metres). size: every weapon in first person is drawn',
       '--     this much larger than the web game\'s scale (Viewmodel: k = S x vm.s x size), the hands with it',
       '--   katana: its rest and parry poses as a turn and a shift laid over the web game\'s clips, and when each is on',
       '--   looks: each weapon\'s before / after / combined pose, use = the one in play (the flat shift / scale / tilt /',
       '--     aimZ are that one); a player\'s HoldLook attribute shows another on every weapon (Viewmodel.look).',
       '--     shredderVM: the Shredder\'s first-person grip spot and aim point per look (camera space, studs)',
       'local V = Vector3.new',
       'return {',
       '\telbow = { Right = %s, Left = %s },' % (V(H['_elbow']['R']), V(H['_elbow']['L'])),
       '\tsize = %s,' % f(H.get('_size', 1))]
out.append('\tholds = {')
for wid, h in H.items():
    if wid.startswith('_'): continue
    sides = []
    for side, long in (('R', 'Right'), ('L', 'Left')):
        s = h.get(side)
        if not s: continue
        assert s['pose'] in ('grip', 'fist', 'cradle', 'wrap', 'palm'), (wid, side, s['pose'])
        extra = ''
        if s.get('elbow'): extra += ', elbow = %s' % V(s['elbow'])
        if s.get('turn'): extra += ', turn = %s' % f(math.radians(s['turn']))
        sides.append('%s = { pose = "%s", at = %s, rot = %s, size = %s%s }' % (
            long, s['pose'], V(s['at']), V([math.radians(a) for a in s.get('rot', (0, 0, 0))]), f(s.get('size', 1)), extra))
    def pose(p):
        bits = []
        if p.get('shift'): bits.append('shift = %s' % V(p['shift']))
        if p.get('scale'): bits.append('scale = %s' % f(p['scale']))
        if p.get('tilt'): bits.append('tilt = %s' % V([math.radians(a) for a in p['tilt']]))
        if p.get('aimZ'): bits.append('aimZ = %s' % f(p['aimZ']))
        return bits
    if h.get('looks'):
        sides += pose(h['looks'][h['use']])  # (the used look, flat, for any reader that doesn't know looks)
        sides.append('use = "%s"' % h['use'])
        sides.append('looks = { %s }' % ', '.join('%s = { %s }' % (n, ', '.join(pose(p))) for n, p in h['looks'].items()))
    else:
        sides += pose(h)
    a = h.get('ads')
    if a:
        bits = ['aimZ = %s' % f(a.get('aimZ', 0)), 'kind = "%s"' % a.get('kind', 'iron')]
        if a.get('sight'): bits.append('sight = %s' % V(a['sight']))
        sk = []
        for sid, row in a.get('skins', {}).items():
            sb = []
            if 'aimZ' in row: sb.append('aimZ = %s' % f(row['aimZ']))
            if row.get('sight'): sb.append('sight = %s' % V(row['sight']))
            if row.get('hide'): sb.append('hide = { %s }' % ', '.join('"%s"' % n.lower() for n in row['hide']))
            nr = row.get('near')
            if nr: sb.append('near = { pieces = { %s }, scale = %s, pivot = %s }' % (
                ', '.join('"%s"' % n.lower() for n in nr['pieces']), f(nr['scale']), V(nr['pivot'])))
            sk.append('%s = { %s }' % (sid, ', '.join(sb)))
        if sk: bits.append('skins = { %s }' % ', '.join(sk))
        sides.append('ads = { %s }' % ', '.join(bits))
    out.append('\t\t%s = { %s },' % (wid, ', '.join(sides)))
out.append('\t},')
fx = L.katana_fixes(H)
out.append('\tkatana = {')
out.append('\t\tfixes = {')
for name, (Rm, P) in fx.items():
    out.append('\t\t\t%s = { rot = %s, pos = %s },' % (name, CF(Rm), V(P)))
out.append('\t\t},')
out.append('\t\tclips = {')
for clip, keys in L.KATANA_CLIPS.items():
    out.append('\t\t\t%s = { %s },' % (clip, ', '.join('{ t = %s, fix = "%s" }' % (f(t), n) for t, n in keys)))
out.append('\t\t},')
kl = H['katana']
out.append('\t\tuse = "%s",' % kl['use'])
out.append('\t\tlooks = {')
for name in kl['looks']:
    Rm, Pp = L.katana_fixes(H, look=name)['rest']
    out.append('\t\t\t%s = { rest = { rot = %s, pos = %s } },' % (name, CF(Rm), V(Pp)))
out.append('\t\t},')
out.append('\t},')
sv = H['shredder']
out.append('\tshredderVM = { use = "%s", looks = { %s } },' % (sv['vm_use'], ', '.join(
    '%s = { pos = %s, aim = %s }' % (n, V(p['pos']), V(p['aim'])) for n, p in sv['vm_looks'].items())))
out.append('}')
path = os.path.join(L.ROOT, 'roblox/src/shared/Holds.luau')
open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', path, len(out), 'lines')
