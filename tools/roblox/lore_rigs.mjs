// writes roblox/src/shared/LoreRigs.luau from the dumps (lore_dump.mjs, hr_dump.mjs, cast_meshes.py) + pieces.json
// (lore_meshes.py) + the asset ids
// usage: node lore_rigs.mjs <dump_dir> <pieces.json> <assets.json> <out.luau>
import fs from 'node:fs';
const [dumpDir, piecesFile, assetsFile, outFile] = process.argv.slice(2);
const pieces = JSON.parse(fs.readFileSync(piecesFile, 'utf8'));
const assets = JSON.parse(fs.readFileSync(assetsFile, 'utf8'));
const n = (v) => (Math.abs(v) < 1e-6 ? '0' : String(+v.toFixed(4)));
const vec = (a) => `{${a.map(n).join(', ')}}`;
let o = `--!strict
-- GENERATED by tools/roblox/lore_rigs.mjs (do not edit by hand): the hidden NPCs' rigs, from the web's own code and
-- models (lore_dump.mjs: the five ☺ CORP staff; hr_dump.mjs: the Tall Guy From HR; cast_dump.mjs + cast_meshes.py: the
-- story cast's own Blender models on their code skeletons).
-- Each NPC: asset (the upload: one MeshPart per piece), tilt (the web's head tilt, cast only), joints in parent-first
-- order, pieces.
--   joint: parent, cf (its rest frame in its parent joint's frame: x,y,z studs + quaternion x,y,z,w), pos (the web's
--   local position, metres), rot (the web's Euler XYZ, radians), k (studs per web metre at this joint's parent). Each
--   frame: joint = parent * pre * CFrame.new(pos * k) * Angles(rot), pre = cf * (CFrame.new(pos * k) * Angles(rot))^-1
--   at rest (LoreLife: the web's update() writes into pos / rot)
--   piece: joint, at (its middle in the joint's frame, studs), glass (the see-through part)
-- The web's axes are Roblox's (y up, a body faces -z), so nothing is turned.
local R = {}
`;
for (const fn of fs.readdirSync(dumpDir).filter((f) => f.endsWith('.json')).sort()) {
  const D = JSON.parse(fs.readFileSync(`${dumpDir}/${fn}`, 'utf8'));
  const id = D.id, P = pieces[id] || {};
  o += `R.${id} = {\n\tasset = ${assets[id] || 0},\n`;
  if (D.tilt) o += `\ttilt = ${n(D.tilt)},\n`;
  o += `\tjoints = {\n`;
  // parents before children (the cast's skeleton lists the head before its neck)
  const done = new Set(), ordered = [];
  while (ordered.length < D.joints.length) {
    let moved = false;
    for (const j of D.joints) if (!done.has(j.name) && (!j.parent || done.has(j.parent))) { ordered.push(j); done.add(j.name); moved = true; }
    if (!moved) throw new Error('joint loop in ' + id);
  }
  for (const j of ordered) {
    o += `\t\t{ name = "${j.name}", parent = ${j.parent ? `"${j.parent}"` : 'nil'}, cf = ${vec(j.cf)}, pos = ${vec(j.pos)}, rot = ${vec(j.rot)}, k = ${n(j.posScale)}${j.moves ? ', moves = true' : ''} },\n`;
  }
  o += `\t},\n\tpieces = {\n`;
  for (const [name, p] of Object.entries(P).filter(([k]) => !k.startsWith('_'))) {
    o += `\t\t["${name}"] = { joint = "${p.joint}", at = ${vec(p.centre)}${p.glass ? ', glass = true' : ''} },\n`;
  }
  o += `\t},\n}\n`;
}
o += `return R\n`;
fs.writeFileSync(outFile, o);
console.log('wrote', outFile, o.length);
