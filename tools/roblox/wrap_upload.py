# The wrap textures' Roblox side: which images still need uploading, their asset ids, and the book Studio builds the
# wraps from.
#
#   py tools/roblox/wrap_upload.py <wraps dir> list            files to upload (new or changed since their upload)
#   py tools/roblox/wrap_upload.py <wraps dir> set <file> <id> [<file> <id> ...]   record uploads
#   py tools/roblox/wrap_upload.py <wraps dir> book            write roblox/studio-tools/WrapBook.luau
#
# Uploads: Open Cloud POST /assets/v1/assets with assetType "Image" (not Decal: an Image upload's id goes straight
# into a SurfaceAppearance), from the Studio-approved upload folder; no monthly cap on images (16 Nov 2026).
# The ids live in roblox/assets/wraps/assets.json, keyed by the file's sha1, so a redrawn map uploads again and an
# unchanged one never does. A flat map (one roughness everywhere) is a tiny shared image, const_rough_NNN.png.
import sys, os, json, hashlib
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
MANIFEST = os.path.join(REPO, 'roblox', 'assets', 'wraps', 'assets.json')
SPEC_COPY = os.path.join(REPO, 'roblox', 'assets', 'wraps', 'wraps.json')
BOOK = os.path.join(REPO, 'roblox', 'studio-tools', 'WrapBook.luau')


def sha(p):
    with open(p, 'rb') as fh: return hashlib.sha1(fh.read()).hexdigest()


def load(p, d):
    return json.load(open(p)) if os.path.exists(p) else d


def const_file(wdir, kind, v):
    name = 'const_%s_%03d.png' % (kind, round(v * 100))
    p = os.path.join(wdir, name)
    if not os.path.exists(p):
        Image.new('L', (8, 8), int(round(v * 255))).save(p)
    return name


def maps_of(wdir, s):
    """{slot: file name} for one wrap: images as drawn, flat roughness / metal as shared constant images"""
    m = s['maps']
    out = {'color': m['color']}
    if isinstance(m.get('normal'), str): out['normal'] = m['normal']
    r = m.get('rough', 0.5)
    out['rough'] = r if isinstance(r, str) else const_file(wdir, 'rough', round(r * 10) / 10)  # (tenths: fewer shared images)
    mt = m.get('metal', 0)
    if isinstance(mt, str): out['metal'] = mt
    elif mt > 0.01: out['metal'] = const_file(wdir, 'metal', round(mt * 20) / 20)
    e = m.get('emit', 0)
    if isinstance(e, str): out['emit'] = e
    elif e > 0.01: out['emit'] = const_file(wdir, 'emit', round(e * 20) / 20)
    return out


def main():
    wdir, cmd, rest = sys.argv[1], sys.argv[2], sys.argv[3:]
    spec = load(os.path.join(wdir, 'wraps.json'), {})
    man = load(MANIFEST, {})
    if cmd == 'list':
        seen = set()
        for wid, s in spec.items():
            for slot, f in maps_of(wdir, s).items():
                if f in seen: continue
                seen.add(f)
                h = sha(os.path.join(wdir, f))
                if h not in man: print(os.path.join(wdir, f))
    elif cmd == 'set':
        for f, i in zip(rest[0::2], rest[1::2]):
            p = f if os.path.isabs(f) else os.path.join(wdir, f)
            man[sha(p)] = {'file': os.path.basename(p), 'id': int(i)}
        os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
        json.dump(man, open(MANIFEST, 'w'), indent=1)
        print('recorded', len(rest) // 2)
    elif cmd == 'book':
        rows, missing = [], []
        for wid in sorted(spec):
            s = spec[wid]
            ids, gap = {}, False
            for slot, f in maps_of(wdir, s).items():
                e = man.get(sha(os.path.join(wdir, f)))
                if not e: missing.append(f); gap = True; continue
                ids[slot] = e['id']
            if gap: continue  # (a wrap goes in the book only once every one of its maps is uploaded)
            fields = ', '.join('%s = %d' % (k, ids[k]) for k in ('color', 'normal', 'rough', 'metal', 'emit') if k in ids)
            mt = s['maps'].get('metal', 0)
            finish = 'SHINY' if (isinstance(mt, str) or mt >= 0.5) else 'GLOWS' if 'emit' in ids else ''
            rows.append('\t%s = { %s, emissive = %s, tint = "%s", finish = "%s" },' % (wid, fields, s.get('emissive', 1), s.get('tint', 'ffffff'), finish))
        out = ['--!nocheck',
               '-- GENERATED by tools/roblox/wrap_upload.py book (from the drawn maps, wrap_textures.py, and their image ids in',
               '-- roblox/assets/wraps/assets.json). Do not edit. Run the whole file in Studio (execute_luau, Edit): it builds',
               '-- ReplicatedStorage.JankfireWraps, one SurfaceAppearance per textured wrap (their maps can only be set in Edit),',
               '-- which WeaponModels.wrap clones onto every UV\'d piece of a gun. Returns how many it built.',
               'local BOOK = {'] + rows + ['}', '''
local RS = game:GetService("ReplicatedStorage")
local folder = RS:FindFirstChild("JankfireWraps") or Instance.new("Folder")
folder.Name = "JankfireWraps"
local function id(n) return "rbxassetid://" .. n end
local built = 0
for wid, b in BOOK do
	local sa = folder:FindFirstChild(wid) or Instance.new("SurfaceAppearance")
	sa.Name = wid
	sa.AlphaMode = Enum.AlphaMode.Overlay
	sa.ColorMap = id(b.color)
	sa.NormalMap = if b.normal then id(b.normal) else ""
	sa.RoughnessMap = if b.rough then id(b.rough) else ""
	sa.MetalnessMap = if b.metal then id(b.metal) else ""
	sa.EmissiveMaskContent = if b.emit then Content.fromUri(id(b.emit)) else Content.none
	sa.EmissiveStrength = if b.emit then b.emissive else 0
	sa.EmissiveTint = Color3.fromHex(b.tint)
	sa:SetAttribute("Swatch", id(b.color)) -- the loadout's chip shows the colour map
	sa:SetAttribute("Finish", if b.finish ~= "" then b.finish else nil) -- and this word (GLOWS / SHINY) in its corner
	sa.Parent = folder
	built += 1
end
for _, c in folder:GetChildren() do if not BOOK[c.Name] then c:Destroy() end end
folder.Parent = RS
return built
''']
        with open(BOOK, 'w', newline='\n') as fh: fh.write('\n'.join(out))
        json.dump(spec, open(SPEC_COPY, 'w'), indent=1)
        print('BOOK', BOOK, len(rows), 'wraps', ('MISSING ' + ' '.join(sorted(set(missing)))) if missing else '')


if __name__ == '__main__':
    main()
