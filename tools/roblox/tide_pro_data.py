# The pro animator's Tidecrest cutscene (26 Nov 2026; the original .rbxm stays in the vault, never in git) -> the game's
# data module for it: the animator's camera (a CFrame and field of view per 24 fps frame, the shot numbers, the cuts) and
# the blade's stretch per frame, read out of the file's CameraTrack and BladeStretch ModuleScripts as numbers (nothing in
# the file is run). Writes roblox/src/client/FinisherProData_inkfall.luau's `src` table; FinisherPro.luau plays it.
#   py -I tools/roblox/tide_pro_data.py <Tidecrest_Cutscene.rbxm> <out.luau> [<scan.json>]
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rbxm_read as R

NUM = r'(-?\d+(?:\.\d+)?(?:e-?\d+)?)'

def sources(path):
    out = {}
    for i in R.load(path):
        if i.cls == 'ModuleScript': out[i.name] = i.props.get('Source', '')
    return out

def camera(src):
    rows = {}
    pat = re.compile(r'\[(\d+)\]\s*=\s*\{\s*cf\s*=\s*CFrame\.new\(([^)]*)\)\s*,\s*fov\s*=\s*' + NUM + r'\s*,\s*shot\s*=\s*(\d+)')
    for m in pat.finditer(src):
        f = int(m.group(1))
        cf = [float(x) for x in m.group(2).split(',')]
        assert len(cf) == 12, (f, cf)
        rows[f] = (cf, float(m.group(3)), int(m.group(4)))
    cuts = [int(x) for x in re.search(r'cuts\s*=\s*\{([^}]*)\}', src).group(1).split(',') if x.strip()]
    return rows, cuts

def stretch(src):
    return {int(m.group(1)): float(m.group(2)) for m in re.finditer(r'\[(\d+)\]\s*=\s*' + NUM, src)}

def g(v, d=4):
    s = ('%.' + str(d) + 'f') % v
    s = s.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s

def stock_lua(path, keep=None):
    """the Studio scan (tools/roblox/tide_pro_scan.luau's JSON): the stock rig's body points per frame, in the take's
    space (from the killer's root at frame 0), and when the blade sits in its sheath (its place against the sheath)"""
    S = json.load(open(path, encoding='utf-8'))
    L = ['	-- the stock rig per frame (Studio scan): body points x, y, z in a row per key; the blade home in its sheath (0..1)']
    L.append('	stock = {')
    for k in sorted(S['pts']):
        if keep is not None and k not in keep: continue
        L.append('		%s = { %s },' % (k, ', '.join(g(c, 2) for p in S['pts'][k] for c in p)))
    L.append('	},')
    L.append('	inSheath = { %s },' % ', '.join(g(x, 2) for x in S['inSheath']))
    L.append('	-- the katana against its sheath while it is home (x, y, z, the turn), 0 when it is out')
    L.append('	relS = {')
    for r in S['relS']:
        L.append('		%s,' % ('{ %s }' % ', '.join(g(c, 4) for c in r) if r else '0'))
    L.append('	},')
    return chr(10).join(L)


def main(src_path, out, scan=None, lens=None):
    S = sources(src_path)
    rows, cuts = camera(S['CameraTrack'])
    bl = stretch(S['BladeStretch'])
    n = max(rows) + 1
    assert sorted(rows) == list(range(n)) and sorted(bl) == list(range(n)), (len(rows), len(bl))
    LN = json.load(open(lens)) if lens else None
    L = []
    if LN:
        L.append('\t-- the lens per frame (tools/roblox/tide_lens.py: his camera where it worked, ours where the review found it weak):')
        L.append('\t-- x, y, z, the 3x3 turn (rows), fov - from the killer\'s root at frame 0 on the animator\'s rig')
        cams = LN['lens']
    else:
        L.append('\t-- the animator\'s camera per frame: x, y, z, the 3x3 turn (rows), fov - from the samurai\'s root at frame 0')
        cams = [rows[f][0] + [rows[f][1]] for f in range(n)]
    L.append('\tcam = {')
    for f in range(n):
        c = cams[f]
        L.append('\t\t{ %s },' % ', '.join([g(x, 4) for x in c[:12]] + [g(c[12], 2)]))
    L.append('\t},')
    L.append('\tshot = { %s },' % ', '.join(str(LN['shot'][f] if LN else rows[f][2]) for f in range(n)))
    if LN:
        L.append('\tnames = { %s },' % ', '.join('"%s"' % s for s in LN['names']))
        L.append('\t-- per shot: the body point the lens holds to on the real avatars, and how much')
        L.append('\tanchor = { %s },' % ', '.join('{ "%s", %s }' % (a, g(w, 2)) for a, w in LN['anchor']))
        L.append('\t-- the speed ramps: { frame, speed[, "cut"] } (1 = as he timed it; a "cut" switches at that frame)')
        L.append('\tramp = { %s },' % ', '.join('{ %s }' % ', '.join(([g(r[0], 2), g(r[1], 3)] + (['"cut"'] if len(r) > 2 else []))) for r in LN['ramp']))
    L.append('\t-- the blade\'s length per frame (1 = the package blade, 3.22 studs from the guard face)')
    L.append('\tblade = { %s },' % ', '.join(g(bl[f], 3) for f in range(n)))
    L.append('\tframes = %d, fps = 24, floor = 2.78, -- (his floor: 2.78 under the killer\'s root at frame 0)' % n)
    body = '\n'.join(L)
    head = ("-- GENERATED by tools/roblox/tide_pro_data.py from the pro animator's Tidecrest take (the original file stays in the\n"
            "-- vault: Exports\\Tidecrest cutscene (pro animator)) and our lens over it (tools/roblox/tide_lens.py): the lens, the\n"
            "-- shots, the speed ramps, the blade's stretch per 24 fps frame, and the stock rig's body points per frame (the lens\n"
            "-- follows the real avatars by them, tools/roblox/tide_pro_scan.py). client/FinisherPro.luau plays it. Do not\n"
            "-- hand-edit: re-run the tools.\n")
    extra = ''
    if scan and os.path.exists(scan):
        keep = None
        if LN:
            keep = sorted({a for a, _ in LN['anchor']})
        extra = '\n' + stock_lua(scan, keep)
    open(out, 'w', encoding='utf-8', newline='\n').write(head + 'return { inkfall = {\n' + body + extra + '\n} }\n')
    print('wrote', out, n, 'frames', os.path.getsize(out), 'bytes')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None, sys.argv[4] if len(sys.argv) > 4 else None)
